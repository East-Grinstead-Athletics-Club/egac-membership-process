-- ------------------------------------------------------------
-- enquiries
-- Core table for all inbound interest — public form submissions.
-- Events are stored as a JSON array for a lightweight audit trail
-- without a separate table (keeping D1 request count low).
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS enquiries (
  id          TEXT PRIMARY KEY,
  created_at  TEXT NOT NULL,
  name        TEXT,
  email       TEXT NOT NULL,
  phone       TEXT,
  interest    TEXT,                         -- 'junior_athletics' | 'academy' | 'general'
  training_days TEXT DEFAULT '[]',          -- JSON array: ["Tuesday"]
  dob         TEXT,                         -- ISO date: YYYY-MM-DD
  source      TEXT DEFAULT 'website',
  processed   INTEGER DEFAULT 0,            -- 0 = pending, 1 = processed (SQLite BOOLEAN)
  note        TEXT,                         -- admin notes
  raw_payload TEXT,                         -- JSON string: original form POST body
  events      TEXT DEFAULT '[]',            -- JSON array of EnquiryEvent objects
  invite_id   TEXT,                         -- FK to invites (denormalised for quick lookup)
  environment TEXT DEFAULT 'production'     -- 'development' | 'staging' | 'production'
);

CREATE INDEX IF NOT EXISTS enquiries_email_idx         ON enquiries(email);
CREATE INDEX IF NOT EXISTS enquiries_created_at_idx    ON enquiries(created_at);
CREATE INDEX IF NOT EXISTS enquiries_processed_idx     ON enquiries(processed);
CREATE INDEX IF NOT EXISTS enquiries_environment_idx   ON enquiries(environment);
CREATE INDEX IF NOT EXISTS enquiries_email_created_idx ON enquiries(email, created_at);

-- ------------------------------------------------------------
-- invites
-- One invite token per enquiry for the booking flow.
-- Token is a 24-char hex string generated by crypto.randomUUID.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS invites (
  id              TEXT PRIMARY KEY,
  token           TEXT UNIQUE NOT NULL,
  enquiry_id      TEXT NOT NULL,
  created_at      TEXT NOT NULL,
  sent_at         TEXT,
  accepted_at     TEXT,
  status          TEXT DEFAULT 'pending'
                  CHECK (status IN ('pending', 'sent', 'accepted', 'expired')),
  send_attempts   INTEGER DEFAULT 0,
  last_send_error TEXT,
  environment     TEXT DEFAULT 'production',

  FOREIGN KEY (enquiry_id) REFERENCES enquiries(id)
);

CREATE INDEX IF NOT EXISTS invites_token_idx       ON invites(token);
CREATE INDEX IF NOT EXISTS invites_enquiry_idx     ON invites(enquiry_id);
CREATE INDEX IF NOT EXISTS invites_token_status_idx ON invites(token, status);
CREATE INDEX IF NOT EXISTS invites_environment_idx  ON invites(environment);

-- ------------------------------------------------------------
-- bookings
-- Confirmed taster session bookings. One per invite+date combination.
-- Slot values map to age groups: 'u13' (Tue 18:30) | 'u15plus' (Tue 19:30)
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS bookings (
  id              TEXT PRIMARY KEY,
  enquiry_id      TEXT NOT NULL,
  invite_id       TEXT,
  session_date    TEXT NOT NULL,    -- YYYY-MM-DD, must be a Tuesday
  slot            TEXT NOT NULL,    -- 'u13' | 'u15plus'
  session_time    TEXT,             -- HH:MM, derived from slot assignment
  status          TEXT DEFAULT 'confirmed'
                  CHECK (status IN ('confirmed', 'cancelled', 'attended', 'no_show')),
  attendance_note TEXT,
  created_at      TEXT NOT NULL,
  updated_at      TEXT,
  environment     TEXT DEFAULT 'production',

  FOREIGN KEY (enquiry_id) REFERENCES enquiries(id),
  FOREIGN KEY (invite_id)  REFERENCES invites(id)
);

CREATE INDEX IF NOT EXISTS bookings_session_date_slot_idx    ON bookings(session_date, slot);
CREATE INDEX IF NOT EXISTS bookings_enquiry_idx              ON bookings(enquiry_id);
CREATE INDEX IF NOT EXISTS bookings_date_slot_status_idx     ON bookings(session_date, slot, status);
CREATE INDEX IF NOT EXISTS bookings_environment_idx          ON bookings(environment);
-- Prevents a single invite booking the same date twice
CREATE UNIQUE INDEX IF NOT EXISTS bookings_invite_date_uniq  ON bookings(invite_id, session_date)
  WHERE invite_id IS NOT NULL;

-- ------------------------------------------------------------
-- academy_invitations
-- Separate from invites — academy is a waiting list path,
-- not a taster booking. Response recorded as yes/no.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS academy_invitations (
  id           TEXT PRIMARY KEY,
  enquiry_id   TEXT NOT NULL,
  token        TEXT UNIQUE NOT NULL,
  created_at   TEXT NOT NULL,
  sent_at      TEXT,
  responded_at TEXT,
  response     TEXT CHECK (response IN ('yes', 'no', NULL)),
  status       TEXT DEFAULT 'pending'
               CHECK (status IN ('pending', 'sent', 'responded', 'failed')),
  environment  TEXT DEFAULT 'production',

  FOREIGN KEY (enquiry_id) REFERENCES enquiries(id)
);

CREATE INDEX IF NOT EXISTS academy_invitations_token_idx    ON academy_invitations(token);
CREATE INDEX IF NOT EXISTS academy_invitations_enquiry_idx  ON academy_invitations(enquiry_id);
CREATE INDEX IF NOT EXISTS academy_token_status_idx         ON academy_invitations(token, status);
CREATE INDEX IF NOT EXISTS academy_environment_idx          ON academy_invitations(environment);

-- ------------------------------------------------------------
-- age_groups
-- Configurable age group definitions. Seed data provides
-- the two default groups; admins can adjust via the config UI.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS age_groups (
  id                   TEXT PRIMARY KEY,
  code                 TEXT UNIQUE NOT NULL,   -- 'u13' | 'u15plus'
  label                TEXT NOT NULL,          -- Display label
  min_age              INTEGER NOT NULL,
  max_age              INTEGER,                -- NULL = no upper bound
  session_day          TEXT,                   -- 'Tuesday'
  session_time         TEXT,                   -- 'HH:MM'
  capacity_per_session INTEGER DEFAULT 2,
  active               INTEGER DEFAULT 1,      -- 0 | 1
  sort_order           INTEGER DEFAULT 0,
  created_at           TEXT NOT NULL,
  updated_at           TEXT
);

CREATE INDEX IF NOT EXISTS age_groups_code_idx   ON age_groups(code);
CREATE INDEX IF NOT EXISTS age_groups_active_idx ON age_groups(active);

-- ------------------------------------------------------------
-- email_templates
-- HTML email templates with {{variable}} placeholder syntax.
-- Stored in D1 so admins can edit them via the portal without
-- a code deployment.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS email_templates (
  id           TEXT PRIMARY KEY,
  key          TEXT UNIQUE NOT NULL,   -- machine name: 'booking_invite'
  name         TEXT NOT NULL,          -- display name: 'Booking Invitation'
  subject      TEXT NOT NULL,
  html         TEXT NOT NULL,          -- full HTML with {{variables}}
  text_content TEXT,                   -- plain-text fallback
  variables    TEXT DEFAULT '[]',      -- JSON array of allowed variable names
  active       INTEGER DEFAULT 1,
  created_at   TEXT NOT NULL,
  updated_at   TEXT
);

CREATE INDEX IF NOT EXISTS email_templates_key_idx    ON email_templates(key);
CREATE INDEX IF NOT EXISTS email_templates_active_idx ON email_templates(active);

-- ------------------------------------------------------------
-- membership_otps
-- Short-lived one-time tokens sent after a successful taster.
-- Expiry is enforced in application logic (7-day TTL).
-- Migration 0002 adds this table once the booking flow is live.
-- Included here for completeness — idempotent CREATE IF NOT EXISTS.
-- ------------------------------------------------------------
CREATE TABLE IF NOT EXISTS membership_otps (
  id          TEXT PRIMARY KEY,
  enquiry_id  TEXT NOT NULL,
  token       TEXT UNIQUE NOT NULL,
  created_at  TEXT NOT NULL,
  used_at     TEXT,                  -- NULL = unused
  environment TEXT DEFAULT 'production',

  FOREIGN KEY (enquiry_id) REFERENCES enquiries(id)
);

CREATE INDEX IF NOT EXISTS membership_otps_token_idx       ON membership_otps(token);
CREATE INDEX IF NOT EXISTS membership_otps_enquiry_idx     ON membership_otps(enquiry_id);
CREATE INDEX IF NOT EXISTS membership_otps_environment_idx ON membership_otps(environment);
